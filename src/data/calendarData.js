const dayNames = ["Воскресенье","Понедельник","Вторник","Среда","Четверг","Пятница","Суббота"];
const dayShort = ["Вс","Пн","Вт","Ср","Чт","Пт","Сб"];
const slugify = (value) => value.toLowerCase().replace(/[^a-zа-я0-9]+/gi, "_").replace(/^_|_$/g, "");
const formatDate = (value) => value.split("-").reverse().join(".");
const task = (id, platform, text, taskType, folderId, sourceSection = "priority", extra = {}) => ({
  id, platform, text, taskType,
  checklist: platform === "Reels / Shorts / VK Видео"
    ? ["videoReady","coverReady","publishYoutubeShorts","publishVkVideo","publishRutube","publishReels","linksTracked"]
    : platform === "Дзен" || platform === "vc.ru"
      ? ["article","cover","published","tracked"]
      : taskType === "stories"
        ? ["visual","published","tracked"]
        : ["text","visual","published","tracked"],
  sourceSection, folderId, folderSource: "generated", ...extra,
});

